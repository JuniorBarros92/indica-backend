-- Conversas iniciadas por interessados nos anúncios.
create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  service_id bigint not null references public.services(id) on delete cascade,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  seller_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (service_id, buyer_id, seller_id),
  check (buyer_id <> seller_id)
);

alter table public.conversations enable row level security;

drop policy if exists "Participantes podem ver suas conversas" on public.conversations;
create policy "Participantes podem ver suas conversas"
on public.conversations for select
using (auth.uid() = buyer_id or auth.uid() = seller_id);

drop policy if exists "Interessados podem iniciar conversas" on public.conversations;
create policy "Interessados podem iniciar conversas"
on public.conversations for insert
with check (
  auth.uid() = buyer_id
  and exists (
    select 1 from public.services
    where services.id = service_id and services.user_id = seller_id
  )
);

-- Mensagens visíveis apenas aos participantes de cada conversa.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(trim(content)) > 0),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

drop policy if exists "Participantes podem ler mensagens" on public.messages;
create policy "Participantes podem ler mensagens"
on public.messages for select
using (
  exists (
    select 1 from public.conversations
    where conversations.id = conversation_id
      and auth.uid() in (conversations.buyer_id, conversations.seller_id)
  )
);

drop policy if exists "Participantes podem enviar mensagens" on public.messages;
create policy "Participantes podem enviar mensagens"
on public.messages for insert
with check (
  auth.uid() = sender_id
  and exists (
    select 1 from public.conversations
    where conversations.id = conversation_id
      and auth.uid() in (conversations.buyer_id, conversations.seller_id)
  )
);

grant select, insert on public.conversations, public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end;
$$;

